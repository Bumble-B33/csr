package net.bumblebee.claysoldiers.platform;

import net.bumblebee.claysoldiers.ClaySoldiersCommon;
import net.bumblebee.claysoldiers.config.ClientConfig;
import net.bumblebee.claysoldiers.config.CommonConfig;
import net.bumblebee.claysoldiers.config.ServerConfig;
import net.bumblebee.claysoldiers.energy.EnergyColor;
import net.bumblebee.claysoldiers.platform.services.IConfig;
import net.bumblebee.claysoldiers.util.color.ColorHelper;
import net.neoforged.neoforge.common.ModConfigSpec;

import java.util.function.Supplier;

public class NeoForgeConfig implements IConfig, ServerConfig, ClientConfig, CommonConfig {

    private static final ModConfigSpec.Builder SERVER_BUILDER = new ModConfigSpec.Builder();

    private static final ModConfigSpec.BooleanValue CLAY_SOLDIER_MENU_MODIFY = SERVER_BUILDER
            .comment("Whether the Inventory of a clay soldier can be edited via the menu. May cause loss of items.")
            .define(SOLDIER_MODIFY_MENU_KEY, false);
    private static final ModConfigSpec.BooleanValue SHEAR_BLADE_RECIPE = SERVER_BUILDER
            .comment("Enables/Disables the Crafting of Shear Blades from Shears")
            .worldRestart()
            .define(SHEAR_BLADE_RECIPE_KEY, true);

    private static final ModConfigSpec.BooleanValue SOLDIER_DROP_INVENTORY = SERVER_BUILDER
            .comment("Whether Clay Soldiers should drop their Inventory on death")
            .define(SOLDIER_DROP_INVENTORY_KEY, true);

    private static final ModConfigSpec.DoubleValue SOLDIER_DROP_SELF = SERVER_BUILDER
            .comment("Chance for Clay Soldiers to drop them self")
            .defineInRange(SOLDIER_DROP_SELF_KEY, 0.5, 0, 1);

    private static final ModConfigSpec.BooleanValue CHIP_REQUIRES_LOYALTY = SERVER_BUILDER
            .comment("When true Chips can only be installed into Clay Soldiers loyal to the player")
            .define(CHIP_REQUIRES_LOYALTY_KEY, true);

    private static final ModConfigSpec.IntValue BASE_SOLDIER_ENERGY_TRANSFER_RATE = SERVER_BUILDER
            .comment("Energy Transfer Rate for Clay Soldiers with batteries")
            .defineInRange(BASE_SOLDIER_ENERGY_TRANSFER_RATE_KEY, 15, 1, Integer.MAX_VALUE);
    private static final ModConfigSpec.IntValue HAMSTER_WHEEL_SPEED = SERVER_BUILDER
            .comment("Energy per Tick generated by the Hamster Wheel")
            .defineInRange(HAMSTER_WHEEL_SPEED_KEY, 3, 1, Integer.MAX_VALUE);
    private static final ModConfigSpec.IntValue CHARGING_PAD_PLAYER_RATE = SERVER_BUILDER
            .comment("Charging Pad Energy Transfer Rate for the Player")
            .defineInRange(CHARGING_PAD_PLAYER_RATE_KEY, 20, 0, Integer.MAX_VALUE);

    public static final ModConfigSpec SPEC = SERVER_BUILDER.build();

    private static final ModConfigSpec.Builder CLIENT_BUILDER = new ModConfigSpec.Builder();

    private static final ModConfigSpec.BooleanValue STAT_ITEM_SHOW_STATS = CLIENT_BUILDER
            .comment("Whether to show additional info when looking at a Clay Soldiers while holding a Statometer")
            .define(STATO_METER_SHOW_INFO_KEY, true);

    private static final ModConfigSpec.BooleanValue STAT_ITEM_SHOW_COUNT = CLIENT_BUILDER
            .comment("Whether to show the count of Clay Soldiers nearby when holding a Statometer")
            .define(STATO_METER_SHOW_COUNT_KEY, true);

    private static final ModConfigSpec.EnumValue<EnergyColor> ENERGY_COLOR = CLIENT_BUILDER
            .comment("Color of the Energy")
            .defineEnum(ENERGY_COLOR_KEY, EnergyColor.GREEN);


    public static final ModConfigSpec CLIENT_SPEC = CLIENT_BUILDER.build();


    @Override
    public boolean soldierDropInventory() {
        return SOLDIER_DROP_INVENTORY.getAsBoolean();
    }

    @Override
    public float soldierDropSelf() {
        return (float) SOLDIER_DROP_SELF.getAsDouble();
    }

    @Override
    public boolean chipRequiresLoyalty() {
        return CHIP_REQUIRES_LOYALTY.getAsBoolean();
    }

    @Override
    public boolean canModifyClayMobMenu() {
        return CLAY_SOLDIER_MENU_MODIFY.getAsBoolean();
    }

    @Override
    public int baseSoldierEnergyTransferRate() {
        return BASE_SOLDIER_ENERGY_TRANSFER_RATE.getAsInt();
    }

    @Override
    public int chargingPadRatePlayerInventory() {
        return CHARGING_PAD_PLAYER_RATE.get();
    }

    @Override
    public int getHamsterWheelSpeed() {
        return HAMSTER_WHEEL_SPEED.getAsInt();
    }

    @Override
    public boolean statItemShowStats() {
        return STAT_ITEM_SHOW_STATS.getAsBoolean();
    }

    @Override
    public boolean statItemShowCount() {
        return STAT_ITEM_SHOW_COUNT.getAsBoolean();
    }

    @Override
    public int getEnergyColor() {
        return ENERGY_COLOR.get().getColor();
    }

    @Override
    public boolean shearBladeRecipeEnabled() {
        try {
            return SHEAR_BLADE_RECIPE.getAsBoolean();
        } catch (IllegalStateException e) {
            ClaySoldiersCommon.ERROR_HANDLER.error("Trying to access ShearBlade Recipe Config: ", e);
            return true;
        }
    }

    @Override
    public ClientConfig getClientConfig() {
        return this;
    }

    @Override
    public ServerConfig getServerConfig() {
        return this;
    }

    @Override
    public CommonConfig getCommonConfig() {
        return this;
    }
}
